def download(year: int, subject: str, url: str) -> str:
    os.makedirs(RAW, exist_ok=True)
    dst = os.path.join(RAW, f'{SLUG[subject]}_{year}.pdf')
    if os.path.exists(dst) and os.path.getsize(dst) > 10_000:
        return dst
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=180) as r, open(dst, 'wb') as f:
        f.write(r.read())
    return dst


def extract_text(path: str, pages: int = 12) -> str:
    reader = pypdf.PdfReader(path)
    parts = []
    for i in range(min(pages, len(reader.pages))):
        try:
            parts.append(reader.pages[i].extract_text() or '')
        except Exception:
            pass
    return re.sub(r'\s+', ' ', ' '.join(parts))


def verify() -> tuple[int, int]:
    ok = 0
    total = 0
    for year, subject, label, patterns in CHECKS:
        total += 1
        path = os.path.join(RAW, f'{SLUG[subject]}_{year}.pdf')
        if not os.path.exists(path):
            print(f'  ? {year} {subject:22s} | {label}: файл не скачан')
            continue
        text = extract_text(path)
        if all(re.search(p, text) for p in patterns):
            ok += 1
            print(f'  ✓ {year} {subject:22s} | {label}')
        else:
            print(f'  ✗ {year} {subject:22s} | {label}: НЕ НАЙДЕНО')
    return ok, total


def main() -> None:
    sys.stdout.reconfigure(encoding='utf-8')
    os.makedirs(RAW, exist_ok=True)
    for year, subjects in SOURCES.items():
        for subject, url in subjects.items():
            dst = os.path.join(RAW, f'{SLUG[subject]}_{year}.pdf')
            if os.path.exists(dst) and os.path.getsize(dst) > 10_000:
                continue
            try:
                download(year, subject, url)
                print(f'скачано: {os.path.basename(dst)}')
            except Exception as e:
                print(f'ОШИБКА скачивания {url}: {e}')

    print('\nКонтрольные значения по PDF ФИПИ:')
    ok, total = verify()

    csv_path = os.path.join(OUT, 'ege-stem-2015-2025.csv')
    fields = ['год', 'предмет', 'участников_тыс', 'средний_балл', 'источник', 'статус', 'примечание']
    with open(csv_path, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=fields, delimiter=';')
        w.writeheader()
        w.writerows(ROWS)

    print(f'\nCSV: {os.path.basename(csv_path)} — {len(ROWS)} строк')
    for subject in (MATH, PHYS, INF):
        subset = [r for r in ROWS if r['предмет'] == subject]
        done = sum(1 for r in subset if r['статус'] == 'собрано')
        part = sum(1 for r in subset if r['статус'] == 'частично')
        missing = sum(1 for r in subset if r['статус'] == 'искали, не нашли')
        print(f'  {subject:24s}: собрано {done}, частично {part}, не найдено {missing}')
    print(f'Контроль ФИПИ: {ok}/{total}')


if __name__ == '__main__':
    main()
