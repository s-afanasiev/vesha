def write_csv(filename: str, fields: list, rows: list) -> None:
    path = os.path.join(OUT, filename)
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f, delimiter=';')
        w.writerow(fields)
        w.writerows(rows)
    print(f'записано: {filename} — {len(rows)} строк')


