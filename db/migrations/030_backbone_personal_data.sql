-- Два блокера 152-ФЗ перед первым живым покупателем (docs/backbone-handover.md §6–7):
-- реквизиты оператора в политике ПДн витрины и удаление данных покупателя — по его
-- запросу кнопкой в кабинете и по сроку хранения (раз в сутки), а не SQL вручную.

-- Оператор персональных данных — юрлицо или ИП магазина: так его называет политика.
-- { name, inn, ogrn, address, email }: ИНН и ОГРН (ОГРНИП) проверены формой магазина по
-- длине и контрольной цифре до базы; email — почта для обращений по ПДн, null — почта
-- магазина (reply_to). NULL целиком — реквизиты не заполнены: политика неполная.
ALTER TABLE backbone_shops ADD COLUMN operator JSONB;

-- Данные покупателя обезличены: имя, контакт, текст и файл заявки, ключи гостя и
-- содержимого, письма, переписка ассистента. Номер, позиции черновика без контактов,
-- суммы и события журнала остаются — на них держатся замеры. Кто и когда — событие
-- personal_data_erased в журнале магазина.
ALTER TABLE backbone_orders ADD COLUMN erased_at TIMESTAMPTZ;

-- Автоочистка по сроку хранения: заявки магазина, данные которых ещё не обезличены, по дате.
CREATE INDEX backbone_orders_keep_idx ON backbone_orders (shop_id, created_at) WHERE erased_at IS NULL;
