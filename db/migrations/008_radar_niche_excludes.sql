-- засчитывается, даже если её синонимы сработали; вето предка снимает и детей
-- (docs/idea-radar-architecture.md; П14: правило с вердиктом, а не голый bool).
ALTER TABLE radar_niches ADD COLUMN excludes TEXT[] NOT NULL DEFAULT '{}';

