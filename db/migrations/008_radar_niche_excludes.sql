-- «водител» и «автомоб» ловили ДТП и штрафы за парковку. Список пополняется по
-- наблюдениям: вердикт матча показывает сработавший синоним и совпавший текст.
UPDATE radar_niches SET excludes = ARRAY['дтп', 'штраф за парковк'] WHERE slug = 'auto';
