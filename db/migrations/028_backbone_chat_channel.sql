-- Костяк: разговоры ассистента магазинов — своя территория chat-engine (проверка
-- изоляции магазинов, docs/backbone-architecture.md §6.4, §9). Таблицы chat_engine_*
-- общие с демо chat-engine Vesha, а его ручки открыты: через них читались и
-- правились разговоры покупателей любого магазина, а общая персона демо уходила в
-- черновики менеджеров всех магазинов. Теперь репозиторий каждой территории видит
-- только свои каналы: демо — web, магазины — shop; персона магазинов — свой ключ.

UPDATE chat_engine_dialogues d SET channel = 'shop'
FROM backbone_shops s
WHERE d.channel = 'web' AND d.visitor_key LIKE s.id::text || ':%';

INSERT INTO chat_engine_settings (key, value) VALUES (
  'backbone.persona',
  E'Ты — ассистент менеджера магазина: помогаешь отвечать покупателям в чате на сайте.\nТон: вежливый, живой, по-человечески, без канцелярита. Обращайся на «вы».\nОбъём: 2–5 предложений, по делу.\nПравила:\n— не выдумывай сроки и условия: пользуйся только тем, что есть в переписке;\n— если данных не хватает — задай один вежливый уточняющий вопрос;\n— не обещай то, что должен подтвердить менеджер;\n— пиши от первого лица от лица магазина.'
) ON CONFLICT (key) DO NOTHING;
