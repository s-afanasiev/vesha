// Ядро + пакет ниши. Пакета нет — только ядро: на трёх разных нишах ядро покрыло
// всё (вне справочника — 1 сигнал из 978), пакеты почти не понадобились.
class NeedCatalog {
  constructor({ pack = null, label = 'локальный бизнес' } = {}) {
    const p = (pack && PACKS[pack]) || { label, services: [], needs: {} };
    this.version = 'v2';
    this.label = p.label;
    this.needs = { ...CORE, ...p.needs, other: 'потребность, которой нет в справочнике (в detail — какая)' };
    this.services = [...p.services, 'other'];
    this.packNeeds = p.needs;
  }

  known(need) {
    return Object.prototype.hasOwnProperty.call(this.needs, need);
  }
}

module.exports = { NeedCatalog, CORE, PACKS, AUTHORS };
